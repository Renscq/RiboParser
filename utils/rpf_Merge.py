# Function: Merge RPF density files from multiple samples in JSONL or legacy TXT format.
# Input: Sample list table with sample names and RPF density files.
# Output: Merged multi-sample JSONL and/or merged legacy TXT density table.

"""Command-line entry point for merging RPF density files.

The script supports two density formats:

1. Compact JSONL generated by the updated ``rpf_Density``.
   The merged JSONL stores one transcript record per line, with all sample
   densities under the ``samples`` field. Annotation, sequence, and genome
   mapping are stored once per transcript.

2. Legacy codon-level TXT generated by the old or compatibility density output.
   The merged TXT keeps the original codon-level table layout and appends
   three frame columns per sample.
"""

from __future__ import annotations

import argparse
import copy
import csv
import gzip
import json
import os
from collections import OrderedDict
from typing import Dict, Iterable, Iterator, List, Optional, Tuple

import pandas as pd
import polars as pl

from utils.ribo.ArgsParser import args_print, file_check, now_time


SPARSE_ENCODING = "sparse_codon_frame"
DENSE_ENCODING = "dense_codon_frame"
JSON_SUFFIXES = (".jsonl", ".json", ".jsonl.gz", ".json.gz")


def rpf_merge_args_parser():
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(description="Merge RPF density files from different samples.")

    input_group = parser.add_argument_group("Required arguments")
    input_group.add_argument(
        "-l",
        dest="list",
        required=True,
        type=str,
        help="Sample list in TXT format. The first two columns must be sample name and density file.",
    )
    input_group.add_argument(
        "-o",
        dest="output",
        required=True,
        type=str,
        help="Output prefix.",
    )

    parser.add_argument(
        "--input-format",
        dest="input_format",
        choices=["auto", "json", "txt"],
        default="auto",
        help="Input density format. Default: %(default)s.",
    )
    parser.add_argument(
        "--output-format",
        dest="output_format",
        choices=["auto", "json", "txt", "both"],
        default="auto",
        help=(
            "Output format. For JSON input, auto writes merged JSONL. "
            "For TXT input, auto writes merged TXT. Default: %(default)s."
        ),
    )

    args = parser.parse_args()
    file_check(args.list)
    args_print(args)
    return args


def _open_text(path: str, mode: str = "rt"):
    """Open plain text or gzip-compressed text by filename suffix."""
    if path.endswith(".gz"):
        return gzip.open(path, mode, encoding="utf-8")
    return open(path, mode, encoding="utf-8")


def read_sample_list(sample_list: str) -> OrderedDict:
    """Read the sample list table.

    The first two columns are interpreted as sample name and density file.
    Additional columns are ignored for backward compatibility.
    """
    sp_list = pd.read_csv(sample_list, header=0, names=None, sep="\t")

    if sp_list.shape[1] < 2:
        raise ValueError("Sample list must contain at least two columns: sample name and density file.")

    sp_dict = OrderedDict()
    for _, rec in sp_list.iterrows():
        sample_name = str(rec.iloc[0]).strip()
        sample_file = str(rec.iloc[1]).strip()
        if not sample_name or not sample_file:
            continue
        sp_dict[sample_name] = sample_file

    if not sp_dict:
        raise ValueError("No valid samples were found in the sample list.")

    for sample_file in sp_dict.values():
        file_check(sample_file)

    return sp_dict


def _looks_like_json_density_file(path: str) -> bool:
    """Return True if a file appears to be a compact density JSON/JSONL file."""
    lower_path = path.lower()
    if lower_path.endswith(JSON_SUFFIXES):
        return True

    try:
        with _open_text(path, "rt") as inp:
            for line in inp:
                line = line.strip()
                if not line:
                    continue
                return line.startswith("{") and '"record_type"' in line
    except UnicodeDecodeError:
        return False

    return False


def detect_density_format(sp_dict: OrderedDict, requested_format: str = "auto") -> str:
    """Detect whether all sample files are JSONL or legacy TXT."""
    if requested_format in {"json", "txt"}:
        return requested_format

    detected = []
    for sample_name, sample_file in sp_dict.items():
        file_format = "json" if _looks_like_json_density_file(sample_file) else "txt"
        detected.append(file_format)
        print("Detected {sample}: {fmt}".format(sample=sample_name, fmt=file_format), flush=True)

    unique_formats = set(detected)
    if len(unique_formats) != 1:
        raise ValueError(
            "Mixed JSON and TXT density files are not supported in one merge run. "
            "Please merge JSON files and TXT files separately."
        )

    return detected[0]


def _normalize_sample_entry(sample_entry: Dict, fallback_profile: Optional[str] = None) -> OrderedDict:
    """Normalize one sample entry to contain profile and density keys."""
    if not isinstance(sample_entry, dict):
        return OrderedDict([("profile", fallback_profile or "NA"), ("density", {})])

    if "density" in sample_entry:
        return OrderedDict(
            [
                ("profile", str(sample_entry.get("profile", fallback_profile or "NA"))),
                ("density", sample_entry.get("density") or {}),
            ]
        )

    # Backward defensive fallback: sample_entry itself may be a density object.
    return OrderedDict([("profile", fallback_profile or "NA"), ("density", sample_entry)])


def _extract_sample_entries(record: Dict, target_sample_name: str) -> OrderedDict:
    """Extract sample density entries from new or legacy JSON records."""
    samples = record.get("samples")

    if isinstance(samples, dict) and samples:
        if len(samples) == 1:
            _, sample_entry = next(iter(samples.items()))
            return OrderedDict([(target_sample_name, _normalize_sample_entry(sample_entry, record.get("profile")))])

        if target_sample_name in samples:
            return OrderedDict(
                [(target_sample_name, _normalize_sample_entry(samples[target_sample_name], record.get("profile")))]
            )

        # If a merged JSONL is provided as input, preserve all sample names.
        return OrderedDict(
            (str(sample_name), _normalize_sample_entry(sample_entry, record.get("profile")))
            for sample_name, sample_entry in samples.items()
        )

    # Backward compatibility for rpf_Density.001-.007 JSON records.
    return OrderedDict(
        [
            (
                target_sample_name,
                OrderedDict(
                    [
                        ("profile", str(record.get("profile", "NA"))),
                        ("density", record.get("density") or {}),
                    ]
                ),
            )
        ]
    )


def _base_transcript_record(record: Dict) -> OrderedDict:
    """Create a merged transcript record without sample-specific density."""
    remove_keys = {"sample", "profile", "density", "samples"}
    merged = OrderedDict((key, copy.deepcopy(value)) for key, value in record.items() if key not in remove_keys)
    merged["samples"] = OrderedDict()
    return merged


def _transcript_key(record: Dict) -> str:
    """Return a stable transcript key for merging."""
    return str(record.get("transcript_id") or record.get("name") or record.get("gene_id"))


def merge_json_density(sp_dict: OrderedDict, output_prefix: str, output_format: str) -> Tuple[Optional[str], Optional[str]]:
    """Merge compact JSONL density files into a multi-sample JSONL file."""
    merged_records = OrderedDict()
    sample_order = []
    total_input_records = 0

    for sample_name, sample_file in sp_dict.items():
        print("Import the RPF JSONL file: {sample} -> {file}.".format(sample=sample_name, file=sample_file), flush=True)
        imported_records = 0

        with _open_text(sample_file, "rt") as inp:
            for line in inp:
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                if record.get("record_type") != "transcript":
                    continue

                key = _transcript_key(record)
                if key not in merged_records:
                    merged_records[key] = _base_transcript_record(record)

                sample_entries = _extract_sample_entries(record, sample_name)
                for current_sample, sample_entry in sample_entries.items():
                    if current_sample not in sample_order:
                        sample_order.append(current_sample)
                    merged_records[key]["samples"][current_sample] = sample_entry

                imported_records += 1
                total_input_records += 1

        print(
            "Imported transcript records: {count}".format(count=imported_records),
            flush=True,
        )

    out_json = None
    out_txt = None

    if output_format in {"auto", "json", "both"}:
        out_json = output_prefix + "_rpf_merged.jsonl.gz"
        with gzip.open(out_json, "wt", encoding="utf-8") as out:
            for record in merged_records.values():
                out.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")))
                out.write("\n")
        print("Merged RPF JSONL written: {path}".format(path=out_json), flush=True)

    if output_format in {"txt", "both"}:
        out_txt = output_prefix + "_rpf_merged.txt"
        write_json_records_as_legacy_txt(merged_records.values(), sample_order, out_txt)

    summary_file = output_prefix + "_rpf_merged.summary.json"
    summary = OrderedDict(
        [
            ("input_format", "json"),
            ("output_format", output_format),
            ("samples", sample_order),
            ("sample_count", len(sample_order)),
            ("input_record_count", total_input_records),
            ("merged_transcript_count", len(merged_records)),
            ("json_output", out_json or "NA"),
            ("txt_output", out_txt or "NA"),
        ]
    )
    with open(summary_file, "w", encoding="utf-8") as out:
        json.dump(summary, out, indent=2, ensure_ascii=False)
        out.write("\n")
    print("Merged RPF summary written: {path}".format(path=summary_file), flush=True)

    return out_json, out_txt


def _density_to_dense_frames(density: Dict, codon_count: int) -> Tuple[List[int], List[int], List[int]]:
    """Convert one sparse or dense density object to dense frame arrays."""
    if not isinstance(density, dict):
        return [0] * codon_count, [0] * codon_count, [0] * codon_count

    encoding = density.get("encoding", SPARSE_ENCODING)
    if encoding == DENSE_ENCODING:
        f0 = [int(x) for x in density.get("f0", [])]
        f1 = [int(x) for x in density.get("f1", [])]
        f2 = [int(x) for x in density.get("f2", [])]
        if len(f0) < codon_count:
            f0.extend([0] * (codon_count - len(f0)))
        if len(f1) < codon_count:
            f1.extend([0] * (codon_count - len(f1)))
        if len(f2) < codon_count:
            f2.extend([0] * (codon_count - len(f2)))
        return f0[:codon_count], f1[:codon_count], f2[:codon_count]

    f0 = [0] * codon_count
    f1 = [0] * codon_count
    f2 = [0] * codon_count
    frames = (f0, f1, f2)

    for codon_index, frame, count in zip(
        density.get("codon_index", []), density.get("frame", []), density.get("count", [])
    ):
        codon_index = int(codon_index)
        frame = int(frame)
        if 0 <= codon_index < codon_count and frame in (0, 1, 2):
            frames[frame][codon_index] += int(count)

    return f0, f1, f2


def _legacy_header_from_samples(sample_names: List[str]) -> List[str]:
    """Return a merged legacy TXT header."""
    header = ["name", "now_nt", "from_tis", "from_tts", "region", "codon"]
    for sample_name in sample_names:
        header.extend([sample_name + "_f0", sample_name + "_f1", sample_name + "_f2"])
    return header


def _legacy_rows_from_json_record(record: Dict, sample_names: List[str]) -> Iterator[List]:
    """Yield merged legacy TXT rows from one multi-sample JSON record."""
    trim = record["trim"]
    sequence = str(record.get("sequence", ""))
    name = record.get("name", record.get("transcript_id", "NA"))
    samples = record.get("samples") or {}

    codon_count = int(trim["codon_count"])
    start_nt0 = int(trim["start_nt0"])
    trim_length_nt = int(trim["trim_length_nt"])
    utr5_codons = int(trim["utr5_codons"])
    cds_codons = int(trim["cds_codons"])
    utr3_nt = int(trim["utr3_nt"])
    from_tts_start = (utr3_nt - trim_length_nt) // 3 + 1

    frame_arrays = []
    for sample_name in sample_names:
        sample_entry = samples.get(sample_name) or {}
        density = sample_entry.get("density") if isinstance(sample_entry, dict) else {}
        frame_arrays.append(_density_to_dense_frames(density or {}, codon_count))

    for codon_index in range(codon_count):
        codon_start = codon_index * 3
        codon = sequence[codon_start : codon_start + 3].upper()
        if "N" in codon:
            continue

        if codon_index < utr5_codons:
            region = "5utr"
        elif codon_index < utr5_codons + cds_codons:
            region = "cds"
        else:
            region = "3utr"

        sample_values = []
        for f0, f1, f2 in frame_arrays:
            sample_values.extend([int(f0[codon_index]), int(f1[codon_index]), int(f2[codon_index])])

        now_nt = start_nt0 + 1 + codon_index * 3
        from_tis = codon_index - utr5_codons
        from_tts = from_tts_start + codon_index

        yield [name, now_nt, from_tis, from_tts, region, codon] + sample_values


def write_json_records_as_legacy_txt(records: Iterable[Dict], sample_names: List[str], output_txt: str) -> str:
    """Write merged JSON transcript records as a legacy codon-level TXT table."""
    row_count = 0
    with open(output_txt, "w", encoding="utf-8", newline="") as out:
        writer = csv.writer(out, delimiter="\t", lineterminator="\n")
        writer.writerow(_legacy_header_from_samples(sample_names))
        for record in records:
            for row in _legacy_rows_from_json_record(record, sample_names):
                writer.writerow(row)
                row_count += 1

    print("Merged RPF TXT written: {path}".format(path=output_txt), flush=True)
    print("Merged TXT rows written: {count}".format(count=row_count), flush=True)
    return output_txt


def merge_txt_density(sp_dict: OrderedDict, output_prefix: str, output_format: str) -> str:
    """Merge legacy codon-level TXT density files."""
    if output_format not in {"auto", "txt"}:
        raise ValueError("Legacy TXT input can only be merged to TXT output.")

    total_rpf = None
    now_sample_num = 0

    for sp_name, sp_file in sp_dict.items():
        print("Import the RPF TXT file: {sample} -> {file}.".format(sample=sp_name, file=sp_file), flush=True)
        rpf = pl.read_csv(sp_file, separator="\t", has_header=True)

        if rpf.width < 9:
            raise ValueError("Legacy density TXT must contain at least 9 columns: {file}".format(file=sp_file))

        if now_sample_num == 0:
            rpf = rpf[:, [0, 1, 2, 3, 4, 5, 6, 7, 8]]
            rpf.columns = [
                "name",
                "now_nt",
                "from_tis",
                "from_tts",
                "region",
                "codon",
                sp_name + "_f0",
                sp_name + "_f1",
                sp_name + "_f2",
            ]
            total_rpf = rpf
        else:
            rpf = rpf[:, [0, 1, 6, 7, 8]]
            rpf.columns = ["name", "now_nt", sp_name + "_f0", sp_name + "_f1", sp_name + "_f2"]
            total_rpf = total_rpf.join(rpf, on=["name", "now_nt"], how="inner")

        now_sample_num += 1

    output_name = output_prefix + "_rpf_merged.txt"
    total_rpf = total_rpf.with_columns(pl.col("codon").str.to_uppercase())
    total_rpf = total_rpf.filter(~pl.col("codon").str.contains("N"))
    total_rpf.write_csv(output_name, separator="\t", include_header=True)

    print("Merged RPF TXT written: {path}".format(path=output_name), flush=True)
    return output_name


def main():
    now_time()
    print("\nMerge RPF density files from different samples.", flush=True)
    print("\nStep1: Checking the input arguments.", flush=True)
    args = rpf_merge_args_parser()

    print("\nStep2: Import the sample list.", flush=True)
    sp_dict = read_sample_list(args.list)

    print("\nStep3: Detect density file format.", flush=True)
    density_format = detect_density_format(sp_dict, args.input_format)
    print("Density file format: {fmt}".format(fmt=density_format), flush=True)

    print("\nStep4: Merge the RPF density files.", flush=True)
    if density_format == "json":
        merge_json_density(sp_dict, args.output, args.output_format)
    elif density_format == "txt":
        merge_txt_density(sp_dict, args.output, args.output_format)
    else:
        raise ValueError("Unsupported density format: {fmt}".format(fmt=density_format))

    print("\nAll done.", flush=True)
    now_time()


if __name__ == "__main__":
    main()
