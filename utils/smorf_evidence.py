# Input: smorf_cluster tables, scanner ORF table/genePred, and density design.
# Output: Family evidence, reliable smORFs/genePred, and summary.

"""Command-line entry point for family-aware smORF evidence analysis."""

from __future__ import annotations

import argparse
import os
import sys
from argparse import Namespace
from collections.abc import Sequence

# Prevent native thread multiplication inside chromosome worker processes.
for _variable in (
    "OMP_NUM_THREADS",
    "OPENBLAS_NUM_THREADS",
    "MKL_NUM_THREADS",
    "NUMEXPR_NUM_THREADS",
    "VECLIB_MAXIMUM_THREADS",
):
    os.environ.setdefault(_variable, "1")

from utils.ribo.ArgsParser import (  # noqa: E402
    args_print,
    file_check,
    now_time,
    result_print,
    step_print,
    title_print,
)
from utils.smorf.evidence import (  # noqa: E402
    ADVANCED_DEFAULTS,
    MANUAL_THRESHOLD_DEFAULTS,
    run_family_evidence_engine,
)


def _build_parser() -> argparse.ArgumentParser:
    """Build the minimal production parser."""
    parser = argparse.ArgumentParser(
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description=(
            "Evaluate family-aware smORF translation evidence. Biological "
            "thresholds, annotated-ORF calibration, long-ORF rules, and "
            "replication requirements are controlled internally."
        ),
    )

    required = parser.add_argument_group("Required arguments")
    required.add_argument(
        "-i",
        "--family-table",
        dest="family_table",
        required=True,
        type=str,
        help="Input *.family.message.txt generated by smorf_cluster.",
    )
    required.add_argument(
        "-M",
        "--family-members",
        dest="family_members",
        required=True,
        type=str,
        help="Input *.family.members.txt generated by smorf_cluster.",
    )
    required.add_argument(
        "--orf-source",
        dest="orf_source",
        required=True,
        type=str,
        help="Full smorf_scanner message table used by smorf_cluster.",
    )
    required.add_argument(
        "-G",
        "--orf-genepred",
        dest="orf_genepred",
        required=True,
        type=str,
        help=(
            "Complete ORF genePred generated by smorf_scanner. Column 1 "
            "must contain ORF IDs matching --orf-source."
        ),
    )
    required.add_argument(
        "-l",
        "--density-list",
        dest="density_list",
        required=True,
        type=str,
        help=(
            "Tab-delimited density design containing sample/name, group, "
            "strand, and path/file/density columns."
        ),
    )
    required.add_argument(
        "-o",
        "--output",
        dest="output",
        required=True,
        type=str,
        help="Output prefix.",
    )

    evidence = parser.add_argument_group("Evidence arguments")
    evidence.add_argument(
        "--evidence-mode",
        choices=("canonical", "manual"),
        default="manual",
        type=str,
        help=(
            "Use annotated_ORFs for sample-specific calibration or use "
            "the manual balanced thresholds (default: %(default)s)."
        ),
    )
    evidence.add_argument(
        "--group",
        dest="group_column",
        default="group",
        type=str,
        help=("Density-list column containing biological replicate groups (default: %(default)s)."),
    )
    evidence.add_argument(
        "--reliable-sample",
        dest="reliable_sample",
        default=2,
        type=int,
        help=("Minimum independent samples supporting a reliable family (default: %(default)s)."),
    )

    manual = parser.add_argument_group("Manual evidence thresholds")
    manual.add_argument(
        "--min-rpf-sum",
        default=MANUAL_THRESHOLD_DEFAULTS["min_rpf_sum"],
        type=float,
        help="Minimum whole-region P-site count (default: %(default)s).",
    )
    manual.add_argument(
        "--min-rpf-per-codon",
        default=MANUAL_THRESHOLD_DEFAULTS["min_rpf_per_codon"],
        type=float,
        help="Minimum P-sites per codon (default: %(default)s).",
    )
    manual.add_argument(
        "--min-covered-codon",
        default=MANUAL_THRESHOLD_DEFAULTS["min_covered_codon"],
        type=int,
        help="Minimum covered codons (default: %(default)s).",
    )
    manual.add_argument(
        "--min-codon-coverage",
        default=MANUAL_THRESHOLD_DEFAULTS["min_coverage_ratio"],
        type=float,
        help="Minimum covered-codon fraction (default: %(default)s).",
    )
    manual.add_argument(
        "--moderate-periodicity",
        default=MANUAL_THRESHOLD_DEFAULTS["moderate_periodicity"],
        type=float,
        help="Moderate frame-0 fraction (default: %(default)s).",
    )
    manual.add_argument(
        "--strong-periodicity",
        default=MANUAL_THRESHOLD_DEFAULTS["strong_periodicity"],
        type=float,
        help="Strong frame-0 fraction (default: %(default)s).",
    )
    manual.add_argument(
        "--min-window-rpf",
        default=MANUAL_THRESHOLD_DEFAULTS["min_window_rpf"],
        type=float,
        help="Minimum sliding-window P-site count (default: %(default)s).",
    )
    manual.add_argument(
        "--min-window-covered-codon",
        default=MANUAL_THRESHOLD_DEFAULTS["min_window_covered"],
        type=int,
        help="Minimum covered codons per window (default: %(default)s).",
    )

    hidden_defaults = {
        "positive_quantile": 0.20,
        "positive_min_controls": 30,
        "positive_max_controls": 5000,
    }
    for name, default in hidden_defaults.items():
        parser.add_argument(
            "--" + name.replace("_", "-"),
            dest=name,
            default=default,
            type=int if "controls" in name else float,
            help=argparse.SUPPRESS,
        )
    for name in ADVANCED_DEFAULTS:
        parser.add_argument(
            "--" + name.replace("_", "-"),
            dest=name,
            default=None,
            type=(
                float
                if name
                in {
                    "min_signal_span",
                    "localized_span_max",
                    "localized_top_window_fraction",
                    "min_frame_margin",
                    "silent_extension_density_ratio",
                    "noncanonical_override_density_ratio",
                    "noncanonical_override_min_coverage_ratio",
                    "noncanonical_override_min_frame_margin",
                    "nested_min_frame_margin",
                    "nested_min_phase_rpf",
                    "high_overlap_fraction",
                    "overlap_min_frame_margin",
                    "overlap_min_phase_rpf",
                }
                else int
            ),
            help=argparse.SUPPRESS,
        )

    runtime = parser.add_argument_group("Runtime arguments")
    runtime.add_argument(
        "-t",
        "--thread",
        dest="threads",
        default=1,
        type=int,
        help=(
            "Requested chromosome workers. The engine may reduce this value "
            "to protect memory (default: %(default)s)."
        ),
    )
    return parser


def _validate_args(args: Namespace) -> None:
    """Validate the minimal command arguments."""
    file_check(
        args.family_table,
        args.family_members,
        args.orf_source,
        args.orf_genepred,
        args.density_list,
    )
    if args.threads < 1:
        raise ValueError("--thread must be >= 1.")
    if args.reliable_sample < 1:
        raise ValueError("--reliable-sample must be >= 1.")
    if not args.group_column.strip():
        raise ValueError("--group cannot be empty.")
    nonnegative = (
        "min_rpf_sum",
        "min_rpf_per_codon",
        "min_covered_codon",
        "min_window_rpf",
        "min_window_covered_codon",
    )
    for name in nonnegative:
        if getattr(args, name) < 0:
            raise ValueError("--" + name.replace("_", "-") + " must be >= 0.")
    fractions = (
        "min_codon_coverage",
        "moderate_periodicity",
        "strong_periodicity",
        "positive_quantile",
    )
    for name in fractions:
        value = getattr(args, name)
        if not 0.0 <= value <= 1.0:
            raise ValueError("--" + name.replace("_", "-") + " must be in [0, 1].")
    if args.strong_periodicity < args.moderate_periodicity:
        raise ValueError("--strong-periodicity must be >= --moderate-periodicity.")
    if args.positive_min_controls < 1:
        raise ValueError("--positive-min-controls must be >= 1.")
    if args.positive_max_controls < args.positive_min_controls:
        raise ValueError("--positive-max-controls must be >= --positive-min-controls.")


def _parse_args(
    argv: Sequence[str] | None = None,
) -> Namespace:
    """Parse, validate, and print arguments."""
    parser = _build_parser()
    args = parser.parse_args(argv)
    try:
        _validate_args(args)
    except ValueError as error:
        parser.error(str(error))
    args_print(args)
    return args


def main(argv: Sequence[str] | None = None) -> None:
    """Run family-aware smORF evidence analysis."""
    now_time()
    title_print("Evaluate reliable smORF family translation evidence.")

    step_print(1, "Checking the input arguments.")
    args = _parse_args(argv)

    step_print(
        2,
        "Index families, calibrate samples, and evaluate family scaffolds.",
    )
    try:
        result = run_family_evidence_engine(args)
    except Exception as error:
        print(
            f"\nsmorf_evidence failed: {type(error).__name__}: {error}",
            file=sys.stderr,
            flush=True,
        )
        raise

    step_print(3, "Report final smORF evidence.")
    result_print(
        [
            ("Biological samples", result.sample_count),
            ("Effective workers", result.effective_workers),
            ("Total families", f"{result.total_families:,}"),
            ("Reliable families", f"{result.reliable_families:,}"),
            ("Reliable smORFs", f"{result.reliable_smorfs:,}"),
            ("Uncertain families", f"{result.uncertain_families:,}"),
            ("No-evidence families", f"{result.no_evidence_families:,}"),
            ("Family evidence", result.master_output),
            ("Reliable smORFs", result.reliable_output),
            ("Reliable genePred", result.reliable_genepred_output),
            ("Summary", result.summary_output),
        ]
    )

    title_print("All done.")
    now_time()


if __name__ == "__main__":
    main()
