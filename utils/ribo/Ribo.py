    @staticmethod
    def format_rpf_density(args):
        """Deprecated compatibility method for legacy callers.

        This method is intentionally kept minimal. New code should use JSONL
        records and ``json_to_txt`` for compatibility conversion.
        """
        gene_list, mrna_dict, out_prefix = args
        rpf_list = []
        fake_args = type("Args", (), {})()
        fake_args.transcript = "NA"
        fake_args.sequence = "NA"
        fake_args.bam = "NA.bam"
        fake_args.psite = "NA"
        fake_args.periodicity = 0
        fake_args.min_confidence = 0
        fake_args.drop_warning = False
        fake_args.min = 0
        fake_args.max = 999
        fake_args.thread = 1
        fake_args.output = out_prefix
        fake_args.output_format = "txt"
        fake_args.density_encoding = "sparse"
        fake_args.longest = False
        fake_args.silence = True
        ribo = Ribo(fake_args)
        ribo.mrna_dict = OrderedDict((name, mrna_dict[name]) for name in gene_list)
        ribo.profile = "unknown"

        for record in ribo.iter_density_records():
            header = Ribo._legacy_header(ribo.sample_name)
            rows = list(Ribo._legacy_rows_from_record(record))
            if rows:
                rpf_list.append(pd.DataFrame(rows, columns=header))

        if not rpf_list:
            return pd.DataFrame(columns=Ribo._legacy_header(os.path.basename(out_prefix)))
        return pd.concat(rpf_list, ignore_index=True)
