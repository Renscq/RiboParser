"""Core RPF density utilities for RiboParser.

This module converts transcriptome-aligned Ribo-seq BAM/SAM records into
P-site density. The default output is a compact JSONL file with one transcript
record per line. A compatibility converter is provided to expand the JSONL file
back into the legacy codon-level TXT table when downstream modules still require
that format.

Main workflow
-------------
1. Import P-site offsets generated by ``rpf_Offset``.
2. Import transcript annotation from old norm TXT, enhanced norm TXT, or genePred plus transcript FASTA generated by
   ``rpf_Reference``.
3. Scan BAM/SAM alignments and accumulate single-base P-site density arrays.
4. Write one compact JSON record per transcript.
5. Optionally expand JSON records to the legacy TXT table.
"""

