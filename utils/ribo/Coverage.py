    def draw_meta_gene_bar(self) -> None:
        """Draw per-sample percentage barplots of covered transcript bins."""
        if self.coverage is None:
            raise ValueError("Coverage has not been calculated yet.")

        percentage_tables = []

        for sample in self.sample_name:
            high_gene = self._get_high_expression_genes(sample)
            sample_percentage = []

            for region, bins in self._region_bins().items():
                if bins <= 0:
                    continue

                binned_df = self._build_binned_region_table(sample, region, high_gene)
                binned_df["Present"] = (binned_df["RawDensity"] > 0).astype(float)
                percentage = (
                    binned_df.groupby(["Sample", "Region", "Bin", "MetaPosition"], sort=False)["Present"]
                    .mean()
                    .mul(100.0)
                    .rename("Percentage")
                    .reset_index()
                )
                sample_percentage.append(percentage)
                percentage_tables.append(percentage)

            if not sample_percentage:
                continue

            sample_df = pd.concat(sample_percentage, axis=0, ignore_index=True).sort_values("MetaPosition")
            safe_sample = self._safe_name(sample)
            out_pdf = f"{self.output}_{safe_sample}_coverage_bar_plot.pdf"
            out_png = f"{self.output}_{safe_sample}_coverage_bar_plot.png"

            fig = plt.figure(figsize=(9.5, 5.6))
            grid = fig.add_gridspec(nrows=2, ncols=1, height_ratios=[4.2, 0.95], hspace=0.05)
            ax = fig.add_subplot(grid[0, 0])
            gene_ax = fig.add_subplot(grid[1, 0], sharex=ax)

            ax.bar(sample_df["MetaPosition"], sample_df["Percentage"], width=0.9, edgecolor="none")
            ax.set_title("Covered transcript percentage of {sample}".format(sample=sample), fontsize=12)
            ax.set_ylabel("Covered transcripts (%)")
            ax.set_ylim(0, 100)
            self._set_common_axis_style(ax)
            self._set_coverage_xticks(ax, max_ticks=10)
            plt.setp(ax.get_xticklabels(), visible=False)

            self._draw_gene_structure(gene_ax)

            fig.savefig(out_pdf, bbox_inches="tight")
            fig.savefig(out_png, dpi=300, bbox_inches="tight")
            plt.close(fig)

            self.output_files[f"{sample}_coverage_bar_pdf"] = out_pdf
            self.output_files[f"{sample}_coverage_bar_png"] = out_png

        if percentage_tables:
            percentage_df = pd.concat(percentage_tables, axis=0, ignore_index=True)
            out_txt = self.output + "_metagene_coverage_percentage.txt"
            percentage_df.to_csv(out_txt, sep="\t", index=False)
            self.output_files["coverage_percentage"] = out_txt

    def draw_gene_heatmap(self) -> None:
        """Draw optional per-sample transcript-by-position heatmaps."""
        for sample in self.sample_name:
            high_gene = self._get_high_expression_genes(sample)
            if len(high_gene) == 0:
                continue

            region_tables = []
            for region, bins in self._region_bins().items():
                if bins <= 0:
                    continue
                region_tables.append(self._build_binned_region_table(sample, region, high_gene))

            if not region_tables:
                continue

            gene_df = pd.concat(region_tables, axis=0, ignore_index=True)
            gene_df["PlotDensity"] = self._transform_density_values(gene_df["Density"]).to_numpy(dtype=float)
            matrix = gene_df.pivot_table(
                index="Transcript",
                columns="MetaPosition",
                values="PlotDensity",
                aggfunc="mean",
                fill_value=0,
            )
            matrix = matrix.reindex(columns=sorted(matrix.columns))

            # Transcript-level heatmaps are much easier to interpret after
            # row scaling and ordering by peak-position pattern.
            plot_matrix = self._row_minmax_scale(matrix)
            order_df = pd.DataFrame(
                {
                    "PeakPosition": plot_matrix.idxmax(axis=1),
                    "MeanSignal": plot_matrix.mean(axis=1),
                    "MaxSignal": plot_matrix.max(axis=1),
                },
                index=plot_matrix.index,
            ).sort_values(["PeakPosition", "MeanSignal", "MaxSignal"], ascending=[True, False, False])
            plot_matrix = plot_matrix.reindex(order_df.index)

            safe_sample = self._safe_name(sample)
            out_txt = f"{self.output}_{safe_sample}_gene_coverage_matrix.txt"
            out_pdf = f"{self.output}_{safe_sample}_gene_coverage_heatmap.pdf"
            out_png = f"{self.output}_{safe_sample}_gene_coverage_heatmap.png"
            matrix.to_csv(out_txt, sep="	", index=True)

            figure_height = min(max(5.8, len(plot_matrix.index) * 0.005 + 2.4), 18.0)
            fig = plt.figure(figsize=(10.8, figure_height))
            grid = fig.add_gridspec(
                nrows=2,
                ncols=1,
                height_ratios=[max(3.8, figure_height - 1.4), 0.95],
                hspace=0.04,
            )
            ax = fig.add_subplot(grid[0, 0])
            gene_ax = fig.add_subplot(grid[1, 0], sharex=ax)

            x_min, x_max = self._axis_range()
            image = ax.imshow(
                plot_matrix.to_numpy(dtype=float),
                aspect="auto",
                interpolation="nearest",
                cmap=HEATMAP_CMAP,
                vmin=0.0,
                vmax=1.0,
                extent=(x_min - 0.5, x_max + 0.5, len(plot_matrix.index) - 0.5, -0.5),
            )
            ax.set_title(
                "Transcript-level coverage heatmap: {sample} ({count:,} transcripts)".format(
                    sample=sample,
                    count=len(plot_matrix.index),
                ),
                fontsize=12,
            )
            ax.set_ylabel("Transcript")
            ax.set_yticks([])
            positions = [int(value) for value in plot_matrix.columns.tolist()]
            self._set_heatmap_xticks(ax, positions, max_ticks=10)
            ax.axvline(0, color=BOUNDARY_COLOR, linewidth=0.8, linestyle="--", alpha=0.75)
            ax.axvline(self.cds_bin, color=BOUNDARY_COLOR, linewidth=0.8, linestyle="--", alpha=0.75)
            fig.colorbar(image, ax=ax, shrink=0.72, pad=0.015).set_label(
                "Row-scaled " + self._density_axis_label()
            )

            self._draw_gene_structure(gene_ax)

            fig.savefig(out_pdf, bbox_inches="tight")
            fig.savefig(out_png, dpi=300, bbox_inches="tight")
            plt.close(fig)

            self.output_files[f"{sample}_gene_heatmap_table"] = out_txt
            self.output_files[f"{sample}_gene_heatmap_pdf"] = out_pdf
            self.output_files[f"{sample}_gene_heatmap_png"] = out_png

    def run(self, mode: str = "both", draw_barplot: bool = False, draw_gene_heatmap: bool = False) -> None:
        """Run the full coverage workflow."""
        self.import_rpf()
        self.calc_coverage()
        self.output_coverage()

        if mode in {"line", "both", "all"}:
            self.draw_meta_gene_line()
            self.draw_combined_line()
        if mode in {"heatmap", "both", "all"}:
            self.draw_heatmap()
        if draw_barplot or mode == "all":
            self.draw_meta_gene_bar()
        if draw_gene_heatmap:
            print("Warning: --gene-heatmap/--heat is deprecated and no transcript-level heatmap will be drawn.", flush=True)

        self.write_summary()
