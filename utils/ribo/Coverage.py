"""Metagene coverage analysis utilities for RiboParser.

This module calculates normalized 5'UTR-CDS-3'UTR coverage profiles from the
updated RiboParser density format. The RPF import layer is delegated to
``utils.ribo.RPFs.RPFData`` so compact JSONL density files generated by the
updated ``rpf_Density`` / ``rpf_Merge`` workflow and legacy TXT files are both
supported.
"""

