"""RPF density import and transformation utilities for RiboParser.

This module provides a compatibility layer for downstream RiboParser analysis
steps. The public ``import_rpf`` function keeps the historical return structure,
while the internal reader now supports both current compact JSONL density files
and legacy codon-level TXT density files.

Current JSONL records are expected to use the ``samples`` structure generated by
updated ``rpf_Density`` and ``rpf_Merge`` workflows.
"""

