"""RPF density import and transformation utilities for RiboParser.

This module provides a compatibility layer for downstream RiboParser analysis
steps. The public ``import_rpf`` function keeps the historical return structure,
while the internal reader now supports both current compact JSONL density files
and legacy codon-level TXT density files.

Current JSONL records are expected to use the ``samples`` structure generated by
updated ``rpf_Density`` and ``rpf_Merge`` workflows.
"""

from __future__ import annotations

import gzip
import json
import os
import re
import sys
from collections.abc import Iterable, Iterator, Sequence
from dataclasses import dataclass, field
from typing import Any

import pandas as pd
import polars as pl


BASE_COLUMNS = ["name", "now_nt", "from_tis", "from_tts", "region", "codon"]
FRAME_SUFFIXES = ("_f0", "_f1", "_f2")
SPARSE_ENCODING = "sparse_codon_frame"
DENSE_ENCODING = "dense_codon_frame"
PROGRESS_EVERY = 1000


# -----------------------------------------------------------------------------
# Low-level file and type helpers
# -----------------------------------------------------------------------------


def _open_text(path: str, mode: str = "rt"):
    """Open plain text or gzip-compressed text files."""
    if path.endswith(".gz"):
        return gzip.open(path, mode, encoding="utf-8", newline="")
    return open(path, mode, encoding="utf-8", newline="")


def _to_int(value: Any, default: int = 0) -> int:
    """Safely convert one value to integer."""
    try:
        return int(value)
    except (TypeError, ValueError):
        try:
            return int(float(value))
        except (TypeError, ValueError):
            return default


def _detect_rpf_format(rpf_file: str) -> str:
    """Detect RPF density file format as ``json`` or ``txt``."""
    lower_name = rpf_file.lower()

    if lower_name.endswith((".jsonl.gz", ".jsonl", ".json.gz", ".json")):
        return "json"

    if lower_name.endswith((".txt", ".tsv", ".tab")):
        return "txt"

    with _open_text(rpf_file, "rt") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            if line.startswith("{"):
                return "json"
            return "txt"

    raise ValueError(f"Cannot detect density file format from empty file: {rpf_file}")


def _normalize_sample_name(sample_name: str | Sequence[str] | None) -> list[str] | None:
    """Normalize a user-provided sample name argument."""
    if sample_name is None:
        return None
    if isinstance(sample_name, str):
        if not sample_name:
            return None
        return [sample_name]
    return [str(item) for item in sample_name]


def _frame_columns(sample_name: str) -> list[str]:
    """Return three frame column names for one sample."""
    return [f"{sample_name}_f0", f"{sample_name}_f1", f"{sample_name}_f2"]


def _sample_from_frame_column(column: str) -> str:
    """Return sample name from a frame column name."""
    if column.endswith(FRAME_SUFFIXES):
        return column[:-3]
    return column


def _is_frame_column(column: str) -> bool:
    """Return whether one column is a frame density column."""
    return column.endswith(FRAME_SUFFIXES)


# -----------------------------------------------------------------------------
# Gene list and filtering helpers
# -----------------------------------------------------------------------------


def _read_gene_filter(gene: str | None) -> set[str] | None:
    """Read transcript IDs from a gene list file."""
    if not gene:
        return None

    gene_csv = pd.read_csv(gene, header=0, index_col=None, sep="\t")
    if "transcript_id" in gene_csv.columns:
        gene_name = gene_csv["transcript_id"].astype(str).tolist()
    else:
        gene_name = gene_csv.iloc[:, 0].astype(str).tolist()

    return set(gene_name)


def _row_pass_filter(
    name: str,
    codon: str,
    from_tis: int,
    from_tts: int,
    gene_filter: set[str] | None = None,
    tis: int | None = None,
    tts: int | None = None,
) -> bool:
    """Check whether one codon-level row passes common filters."""
    if gene_filter is not None and name not in gene_filter:
        return False

    if tis is not None and from_tis < tis:
        return False

    if tts is not None and from_tts > -tts:
        return False

    if "N" in codon.upper():
        return False

    return True


