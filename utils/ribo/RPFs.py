def read_rpf_file(rpf_file: str) -> pl.DataFrame:
    """Import an RPF density file as a codon-level Polars table.

    Parameters
    ----------
    rpf_file : str
        RPF density file generated by ``rpf_Density`` or ``rpf_Merge``. Both
        current JSONL and legacy TXT formats are supported.

    Returns
    -------
    polars.DataFrame
        Codon-level table with base columns and sample frame columns.
    """
    file_format = _detect_rpf_format(rpf_file)
    if file_format == "json":
        return read_json_rpf_file(rpf_file)
    return read_txt_rpf_file(rpf_file)


def get_frame_rpf(raw_rpf: pl.DataFrame, sample_name: Sequence[str], frame: str) -> pd.DataFrame:
    """Merge all frame density or retrieve one frame as a Pandas table.

    Notes
    -----
    Polars expressions in ``with_columns`` can only reference columns that are
    already present in the dataframe being modified. Therefore this function
    builds the final table directly from the full ``raw_rpf`` dataframe instead
    of first selecting only the six metadata columns.
    """
    frame = str(frame)

    missing_base = [column for column in BASE_COLUMNS if column not in raw_rpf.columns]
    if missing_base:
        raise ValueError(
            "RPF density table is missing required base column(s): {columns}".format(
                columns=", ".join(missing_base)
            )
        )

    select_exprs = [pl.col(column) for column in BASE_COLUMNS]

    if frame == "all":
        for now_sp in sample_name:
            print("Import the density file {file_name}.".format(file_name=now_sp), flush=True)
            f0, f1, f2 = _frame_columns(now_sp)
            missing_frame = [column for column in (f0, f1, f2) if column not in raw_rpf.columns]
            if missing_frame:
                raise ValueError(
                    "RPF density table is missing frame column(s) for sample {sample}: {columns}".format(
                        sample=now_sp,
                        columns=", ".join(missing_frame),
                    )
                )
            select_exprs.append(
                pl.sum_horizontal([pl.col(f0), pl.col(f1), pl.col(f2)]).alias(now_sp)
            )
    elif frame in {"0", "1", "2"}:
        for now_sp in sample_name:
            print("Import the density file {file_name}.".format(file_name=now_sp), flush=True)
            now_sp_index = f"{now_sp}_f{frame}"
            if now_sp_index not in raw_rpf.columns:
                raise ValueError(
                    "RPF density table is missing frame column for sample {sample}: {column}".format(
                        sample=now_sp,
                        column=now_sp_index,
                    )
                )
            select_exprs.append(pl.col(now_sp_index).alias(now_sp))
    else:
        raise ValueError("frame must be one of '0', '1', '2', or 'all'.")

    merged_rpf = raw_rpf.select(select_exprs)
    return merged_rpf.to_pandas()


def set_codon_shift(sites: str) -> int:
    """Set codon shift by E/P/A site."""
    if sites == "E":
        return -1
    if sites == "P":
        return 0
    if sites == "A":
        return 1
    return 0


def shift_site(merged_rpf: pd.DataFrame, sample_name: Sequence[str], shift_num: int) -> pd.DataFrame:
    """Shift codon-level density from P-site to E-site or A-site."""
    if shift_num == 0:
        return merged_rpf

    merged_rpf.loc[:, list(sample_name)] = (
        merged_rpf.groupby("name", sort=False)[list(sample_name)]
        .shift(shift_num)
        .fillna(0)
        .values
    )

    return merged_rpf


def sum_total_rpf(raw_rpf: pl.DataFrame) -> pd.Series:
    """Calculate total RPF count for each sample across all three frames."""
    frame_columns = [column for column in raw_rpf.columns if _is_frame_column(column)]
    if not frame_columns:
        return pd.Series(dtype="int64", name="total_rpf")

    total_rpf_num = raw_rpf.select(frame_columns).sum().to_pandas().T.reset_index()
    total_rpf_num.columns = ["sample_frame", "total_rpf"]
    total_rpf_num["sample"] = total_rpf_num["sample_frame"].map(_sample_from_frame_column)
    total_rpf_num = total_rpf_num.groupby("sample", sort=False)["total_rpf"].sum()

    return total_rpf_num


def high_expression(
    merged_rpf: pd.DataFrame,
    total_rpf_num: pd.Series,
    sample_name: Sequence[str],
    rpf_num: int,
) -> tuple[pd.DataFrame, pd.Index, pd.DataFrame]:
    """Filter high-expression genes using the mean RPF count across samples."""
    gene_rpf_sum = merged_rpf.groupby("name", sort=False)[list(sample_name)].sum()
    high_gene = gene_rpf_sum.loc[gene_rpf_sum.mean(axis=1) >= rpf_num, :].index
    high_rpf = merged_rpf.loc[merged_rpf["name"].isin(high_gene), :]

    return gene_rpf_sum, high_gene, high_rpf


def sum_sample_number(raw_rpf: pl.DataFrame, sample_num: int | None) -> int:
    """Return the number of samples in an RPF table."""
    if sample_num:
        return int(sample_num)

    sample_names = retrieve_sample_name(raw_rpf, None)
    return len(sample_names)


def retrieve_sample_name(
    raw_rpf: pl.DataFrame,
    sample_name: str | Sequence[str] | None,
) -> list[str]:
    """Retrieve sample names from frame density columns."""
    normalized = _normalize_sample_name(sample_name)
    if normalized is not None:
        return normalized

    sample_names = []
    seen = set()
    for column in raw_rpf.columns:
        if not _is_frame_column(column):
            continue
        sample = _sample_from_frame_column(column)
        if sample not in seen:
            sample_names.append(sample)
            seen.add(sample)

    return sample_names


def filter_tis_tts(raw_rpf: pl.DataFrame, tis: int | None, tts: int | None) -> pl.DataFrame:
    """Trim the RPF table by TIS/TTS codon offsets."""
    if tis is not None:
        raw_rpf = raw_rpf.filter(pl.col("from_tis") >= tis)

    if tts is not None:
        raw_rpf = raw_rpf.filter(pl.col("from_tts") <= -tts)

    return raw_rpf


def retrieve_gene_rpf(raw_rpf: pl.DataFrame, gene: str | None) -> pl.DataFrame:
    """Retrieve RPF rows for specific transcript IDs."""
    gene_filter = _read_gene_filter(gene)
    if gene_filter is None:
        return raw_rpf

    return raw_rpf.filter(pl.col("name").cast(pl.Utf8).is_in(list(gene_filter)))


def check_merged_rpf_results(merged_rpf: pd.DataFrame) -> None:
    """Exit if the merged density table is empty."""
    if merged_rpf.empty:
        print("Filtered density table is empty! Please recheck the parameters and data quality.", flush=True)
        sys.exit(1)


def check_high_rpf_results(high_rpf: pd.DataFrame) -> None:
    """Exit if the high-expression density table is empty."""
    if high_rpf.empty:
        print("Filtered density table is empty! Please recheck the parameters and data quality.", flush=True)
        sys.exit(1)


def rpf_to_rpm(raw_rpf: pd.DataFrame | pl.DataFrame, norm: bool):
    """Convert frame density columns to RPM values."""
    if not norm:
        return raw_rpf

    if isinstance(raw_rpf, pl.DataFrame):
        frame_columns = [column for column in raw_rpf.columns if _is_frame_column(column)]
        total_exprs = []
        totals = raw_rpf.select(frame_columns).sum().row(0, named=True)
        for column in frame_columns:
            total = totals.get(column, 0) or 0
            if total > 0:
                total_exprs.append((pl.col(column) * 1_000_000 / total).alias(column))
        return raw_rpf.with_columns(total_exprs)

    frame_columns = [column for column in raw_rpf.columns if _is_frame_column(column)]
    totals = raw_rpf.loc[:, frame_columns].sum(axis=0)
    for column in frame_columns:
        if totals[column] > 0:
            raw_rpf.loc[:, column] = raw_rpf.loc[:, column] * 1_000_000 / totals[column]
    return raw_rpf


@dataclass
class RPFData:
    """Container for codon-level RPF density tables and derived metadata."""

    raw_rpf: pl.DataFrame
    sample_name: list[str]
    sample_num: int
    total_rpf_num: pd.Series
    file_format: str
    source_file: str
    metadata: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def from_file(
        cls,
        rpf_file: str,
        sample_name: str | Sequence[str] | None = None,
        gene: str | None = None,
        tis: int | None = None,
        tts: int | None = None,
    ) -> "RPFData":
        """Create an ``RPFData`` object from JSONL or TXT density input."""
        file_format = _detect_rpf_format(rpf_file)

        if file_format == "json":
            raw_rpf = read_json_rpf_file(
                rpf_file=rpf_file,
                gene=gene,
                tis=tis,
                tts=tts,
                sample_name=sample_name,
            )
        else:
            raw_rpf = read_txt_rpf_file(
                rpf_file=rpf_file,
                gene=gene,
                tis=tis,
                tts=tts,
                sample_name=sample_name,
            )

        samples = retrieve_sample_name(raw_rpf, sample_name)
        totals = sum_total_rpf(raw_rpf)

        return cls(
            raw_rpf=raw_rpf,
            sample_name=samples,
            sample_num=len(samples),
            total_rpf_num=totals,
            file_format=file_format,
            source_file=os.path.abspath(rpf_file),
            metadata={"rows": raw_rpf.height, "columns": raw_rpf.width},
        )

    def get_frame(self, frame: str = "all") -> pd.DataFrame:
        """Return a sample-level codon density table for one or all frames."""
        return get_frame_rpf(self.raw_rpf, self.sample_name, frame)

    def shifted_frame(self, sites: str = "P", frame: str = "all") -> pd.DataFrame:
        """Return frame density shifted to E/P/A site."""
        merged_rpf = self.get_frame(frame=frame)
        shift_num = set_codon_shift(sites)
        return shift_site(merged_rpf, self.sample_name, shift_num)

    def high_expression(
        self,
        rpf_num: int,
        sites: str = "P",
        frame: str = "all",
    ) -> tuple[pd.DataFrame, pd.Index, pd.DataFrame]:
        """Return high-expression transcript summary and table."""
        merged_rpf = self.shifted_frame(sites=sites, frame=frame)
        return high_expression(merged_rpf, self.total_rpf_num, self.sample_name, rpf_num)


def import_rpf(
    rpf_file: str,
    sample_num: int | None,
    sample_name: str | Sequence[str] | None,
    sites: str,
    frame: str,
    gene: str | None,
    rpf_num: int,
    tis: int | None = None,
    tts: int | None = None,
):
    """Import RPF density data using the historical RiboParser return structure.

    Returns
    -------
    tuple
        ``raw_rpf, sample_name, sample_num, merged_rpf, total_rpf_num, gene_rpf_sum, high_gene, high_rpf``.
    """
    # Import and filter the RPF file. JSON input is filtered during expansion to
    # reduce memory use; TXT input is filtered after table import.
    rpf_data = RPFData.from_file(
        rpf_file=rpf_file,
        sample_name=sample_name,
        gene=gene,
        tis=tis,
        tts=tts,
    )

    raw_rpf = rpf_data.raw_rpf
    sample_name = rpf_data.sample_name
    sample_num = int(sample_num) if sample_num else rpf_data.sample_num
    total_rpf_num = rpf_data.total_rpf_num

    # Merge the RPFs of nucleotide frames to codon-level values or retrieve a
    # specific frame.
    merged_rpf = get_frame_rpf(raw_rpf, sample_name, frame)

    # Shift P-site codon density to E-site or A-site when requested.
    shift_num = set_codon_shift(sites)
    merged_rpf = shift_site(merged_rpf, sample_name, shift_num)

    # Filter high-expression genes using the historical mean-count criterion.
    gene_rpf_sum, high_gene, high_rpf = high_expression(
        merged_rpf=merged_rpf,
        total_rpf_num=total_rpf_num,
        sample_name=sample_name,
        rpf_num=rpf_num,
    )

    check_merged_rpf_results(merged_rpf)
    check_high_rpf_results(high_rpf)

    return raw_rpf, sample_name, sample_num, merged_rpf, total_rpf_num, gene_rpf_sum, high_gene, high_rpf


