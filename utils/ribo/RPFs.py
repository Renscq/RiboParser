BASE_COLUMNS = ["name", "now_nt", "from_tis", "from_tts", "region", "codon"]
FRAME_SUFFIXES = ("_f0", "_f1", "_f2")
SPARSE_ENCODING = "sparse_codon_frame"
DENSE_ENCODING = "dense_codon_frame"
PROGRESS_EVERY = 1000
JSON_CHUNK_RECORDS = 512
JSON_BUFFER_SIZE = 8 * 1024 * 1024
