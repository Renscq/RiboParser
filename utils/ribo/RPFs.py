def _read_gene_filter(gene: str | None) -> set[str] | None:
    """Read transcript IDs from a gene list file."""
    if not gene:
        return None

    gene_csv = pd.read_csv(gene, header=0, index_col=None, sep="\t")
    if "transcript_id" in gene_csv.columns:
        gene_name = gene_csv["transcript_id"].astype(str).tolist()
    else:
        gene_name = gene_csv.iloc[:, 0].astype(str).tolist()

    return set(gene_name)


def _row_pass_filter(
    name: str,
    codon: str,
    from_tis: int,
    from_tts: int,
    gene_filter: set[str] | None = None,
    tis: int | None = None,
    tts: int | None = None,
) -> bool:
    """Check whether one codon-level row passes common filters."""
    if gene_filter is not None and name not in gene_filter:
        return False

    if tis is not None and from_tis < tis:
        return False

    if tts is not None and from_tts > -tts:
        return False

    if "N" in codon.upper():
        return False

    return True


