def read_txt_rpf_file(
    rpf_file: str,
    gene: str | None = None,
    tis: int | None = None,
    tts: int | None = None,
    sample_name: str | Sequence[str] | None = None,
) -> pl.DataFrame:
    """Read legacy codon-level TXT RPF density as a Polars table."""
    raw_rpf = pl.read_csv(rpf_file, has_header=True, separator="\t")

    raw_rpf = raw_rpf.with_columns(pl.col("codon").cast(pl.Utf8).str.to_uppercase())
    raw_rpf = raw_rpf.filter(~pl.col("codon").str.contains("N"))

    if gene:
        gene_filter = _read_gene_filter(gene) or set()
        raw_rpf = raw_rpf.filter(pl.col("name").cast(pl.Utf8).is_in(list(gene_filter)))

    raw_rpf = filter_tis_tts(raw_rpf, tis, tts)

    requested_samples = _normalize_sample_name(sample_name)
    if requested_samples is not None:
        keep_columns = BASE_COLUMNS.copy()
        for sample in requested_samples:
            keep_columns.extend(_frame_columns(sample))
        missing_columns = [column for column in keep_columns if column not in raw_rpf.columns]
        if missing_columns:
            raise ValueError(
                "Requested sample frame column(s) not found in TXT density file: {columns}".format(
                    columns=", ".join(missing_columns)
                )
            )
        raw_rpf = raw_rpf.select(keep_columns)

    return raw_rpf


