#!/usr/bin/env python3
# -*- coding: utf-8 -*-

from __future__ import annotations

import re
import subprocess
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "utils" / "data" / "_build_info.py"
PYPROJECT = ROOT / "pyproject.toml"


def run_git_command(args: list[str]) -> str:
    result = subprocess.run(
        ["git", "-C", str(ROOT), *args],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip()


def read_pyproject_version() -> str:
    if not PYPROJECT.exists():
        return "unknown"

    text = PYPROJECT.read_text(encoding="utf-8")

    match = re.search(r'^version\s*=\s*["\']([^"\']+)["\']', text, re.MULTILINE)

    if match:
        return match.group(1)

    return "unknown"


def main():
    version = read_pyproject_version()
    commit = run_git_command(["rev-parse", "--short", "HEAD"])
    commit_date = run_git_command(["log", "-1", "--format=%cs"])
    build_date = datetime.now().strftime("%Y-%m-%d")

    OUT.write_text(
        f'''#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# Auto-generated by scripts/dev/write_build_info.py.
# Do not edit this file manually.

__version__ = "{version}"
__commit__ = "{commit}"
__commit_date__ = "{commit_date}"
__build_date__ = "{build_date}"
''',
        encoding="utf-8",
    )

    print(f"Build info written to: {OUT}")
    print(f"Version: {version}")
    print(f"Commit: {commit}")
    print(f"Commit date: {commit_date}")
    print(f"Build date: {build_date}")


if __name__ == "__main__":
    main()
